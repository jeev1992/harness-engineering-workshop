def settings(without: str | None) -> dict:
    # Hooks run in exec form with this exact interpreter: no shell quoting, no PATH guessing.
    hooks: dict = {}
    if without != "scope-guard":
        hooks["PreToolUse"] = [{
            "matcher": "Write|Edit|MultiEdit|NotebookEdit",
            "hooks": [{
                "type": "command", "command": sys.executable,
                "args": ["${CLAUDE_PROJECT_DIR}/.harness/m1_scope_and_state/hooks/scope_guard.py"],
            }],
        }]
    if without != "stop-gate":
        hooks["Stop"] = [{
            "hooks": [{
                "type": "command", "command": sys.executable,
                "args": ["${CLAUDE_PROJECT_DIR}/.harness/m4_independent_acceptance/hooks/stop_gate.py"],
            }],
        }]
    return {
        "permissions": {
            # Allow rules apply in interactive sessions after you trust the folder.
            "allow": ["Bash(python *)", "Bash(python3 *)", "Bash(git status *)", "Bash(git diff *)", "Bash(git log *)"],
            # Deny rules always apply: the maker may not edit the harness or the plan.
            "deny": ["Edit(/.harness/**)", "Edit(/.claude/**)", "Edit(/plan.json)"],
        },
        "hooks": hooks,
    }


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def write_json(path: Path, value: object) -> None:
    write(path, json.dumps(value, indent=2) + "\n")


def add_harness(project: Path, without: str | None) -> None:
    example = ROOT / "m3_continuity" / "example_repo"
    for name in ("docs/PRODUCT.md", "docs/ARCHITECTURE.md"):
        write(project / name, (example / name).read_text(encoding="utf-8"))
    if without != "router":
        write(project / "AGENTS.md", AGENTS)
        write(project / "CLAUDE.md", "@AGENTS.md\n")
    _, listing = execute("kb list", project)
    write_json(project / "feature_list.json", [
        {"id": "document-listing", "status": "passing", "evidence": {"command": "kb list", "observed": listing}},
        {"id": "delete-command", "status": "not-started", "evidence": {}},
        {"id": "import-command", "status": "not-started", "evidence": {}},
    ])
    write_json(project / "plan.json", {
        "work_item": "Implement document deletion end to end",
        "feature": "delete-command",
        "acceptance": "kb delete-roundtrip",
        "allowed_paths": SCOPE,
        "next_action": "Add a failing test that deletes a document and checks the file and its index entry are gone",
    })
    write(project / "session-handoff.md", (
        "# Session handoff\n\n"
        "## Verified now\n\n- `kb list` reproduces the recorded listing of all three seed documents.\n\n"
        "## Broken or unverified\n\n- delete-command and import-command are not implemented.\n\n"
        "## Next best step\n\n- Implement delete-command as planned in plan.json; "
        "`kb delete-roundtrip` must exit 0.\n"
    ))
    harness = project / ".harness"
    for name in VENDORED:
        write(harness / name, (ROOT / name).read_text(encoding="utf-8"))
    write(harness / "gate.py", WRAPPER.format(target="m4_independent_acceptance/gate.py", args="[str(HERE.parent), *sys.argv[1:]]"))
    write(harness / "doctor.py", DOCTOR)
    write(harness / "observe.py", OBSERVE)
    write_json(project / ".claude" / "settings.json", settings(without))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build a project for the live Claude Code segment.")
    parser.add_argument("target", type=Path)
    parser.add_argument("--harness", choices=("on", "off"), required=True)
    parser.add_argument("--without", choices=CONTROLS, help="leave one control out (ablation)")
    parser.add_argument("--force", action="store_true", help="replace an existing target")
    args = parser.parse_args(argv)

    target = args.target.resolve()
    if target == ROOT or ROOT in target.parents:
        parser.error(f"{target} is inside the workshop repository; Claude Code would load its AGENTS.md. Choose a folder outside it.")
    if args.without and args.harness == "off":
        parser.error("--without needs --harness on")
    if shutil.which("git") is None:
        parser.error("git is required")
    if target.exists():
        if not args.force:
            parser.error(f"{target} exists; pass --force to replace it")
        remove_tree(target)

    create_project(target)
    write(target / "README.md", README)
    if args.harness == "on":
        add_harness(target, args.without)
    init_git(target, "baseline")

    label = f"harness {args.harness}" + (f", without {args.without}" if args.without else "")
    print(f"Created {target} ({label}).")
    print("Next:")
    print(f"  cd {target}")
    print(f'  claude "{PROMPT}"')
    print("Afterwards, from the workshop:")
    print(f"  python instructor/live/score_project.py {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
